/**
 * Builds an offline icon pack for <ok-icon>.
 *
 * Scans sources for literal <ok-icon name="..." set="..."> usages, fetches those icons
 * once from an Iconify-compatible API and returns them as Iconify sets. Registering the
 * result with ok-icon's register(pack, { complete: true }) removes the runtime dependency
 * on the API entirely.
 *
 * Reachable as `okjs icons` — see bin/okjs.js.
 */
import { readFile, readdir } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';

const OK_ICON = /<ok-icon\b([^>]*)>/gi;
const ATTR = (name) => new RegExp(`(?:^|\\s)${name}\\s*=\\s*("([^"]*)"|'([^']*)')`, 'i');
const IGNORED_DIRS = new Set(['node_modules', '.git', 'dist', 'release', 'coverage']);

/**
 * Minimal glob: ** spans directories, * and ? stay within a segment. Enough for the
 * "src/**\/*.html" shape the CLI documents, and one less dependency than pulling in a
 * glob library for it — this ships inside the package.
 */
function globToRegExp(pattern) {
    let out = '';
    for (let i = 0; i < pattern.length; i++) {
        const c = pattern[i];
        if (c === '*') {
            if (pattern[i + 1] === '*') {
                // `**/` may match nothing at all, so that "a/**\/*.js" still finds "a/x.js".
                i++;
                if (pattern[i + 1] === '/') { i++; out += '(?:.*/)?'; }
                else out += '.*';
            } else out += '[^/]*';
        } else if (c === '?') out += '[^/]';
        else out += c.replace(/[.+^${}()|[\]\\]/g, '\\$&');
    }
    return new RegExp(`^${out}$`);
}

async function walk(dir, onFile) {
    let entries;
    try { entries = await readdir(dir, { withFileTypes: true }); }
    catch { return; }
    for (const entry of entries) {
        if (entry.name.startsWith('.') || IGNORED_DIRS.has(entry.name)) continue;
        const full = join(dir, entry.name);
        if (entry.isDirectory()) await walk(full, onFile);
        else await onFile(full);
    }
}

/** Every file under `root` matching one of the glob patterns, as repo-relative paths. */
export async function matchFiles(patterns, root = process.cwd()) {
    const regexes = patterns.map(globToRegExp);
    const found = [];
    await walk(root, (full) => {
        const rel = relative(root, full).split(sep).join('/');
        if (regexes.some(re => re.test(rel))) found.push(rel);
    });
    return found.sort();
}

/**
 * Pull every literal <ok-icon> usage out of one source file.
 * Returns { used: [{ set, name }], dynamic: [{ file, line, attrs }] }.
 */
export function scanSource(source, { file = '', defaultSet = 'lucide' } = {}) {
    const used = [];
    const dynamic = [];
    for (const match of source.matchAll(OK_ICON)) {
        const attrs = match[1];
        const set = attrs.match(ATTR('set'))?.slice(2).find(Boolean) || defaultSet;
        const name = attrs.match(ATTR('name'))?.slice(2).find(Boolean);
        if (name) { used.push({ set, name }); continue; }
        // :name / :set are expressions — nothing to resolve without running the app
        if (/(?:^|\s):(?:name|set)\s*=/.test(attrs)) {
            const line = source.slice(0, match.index).split('\n').length;
            dynamic.push({ file, line, attrs: attrs.trim().slice(0, 80) });
        }
    }
    return { used, dynamic };
}

/**
 * Fetch `names` from one Iconify set, keeping only what a renderer needs.
 * Returns { pack, notFound }.
 */
export async function fetchSet(set, names, { api = 'https://api.iconify.design', fetchImpl = fetch } = {}) {
    const list = [...new Set(names)].sort();
    const url = `${api}/${encodeURIComponent(set)}.json?icons=${list.map(encodeURIComponent).join(',')}`;
    const res = await fetchImpl(url);
    if (!res.ok) throw new Error(`icon set "${set}" responded ${res.status}`);
    const data = await res.json();

    const pack = { prefix: data.prefix || set };
    if (data.width) pack.width = data.width;
    if (data.height) pack.height = data.height;
    pack.icons = data.icons || {};
    // Aliases carry the names that point elsewhere; their parents ride along in icons.
    if (data.aliases && Object.keys(data.aliases).length) pack.aliases = data.aliases;

    return { pack, notFound: data.not_found || [], requested: list };
}

/** Render packs as the ES module `register()` takes, or as raw JSON. */
export function serialize(packs, { format = 'js', name = 'icons.js' } = {}) {
    const body = JSON.stringify(packs, null, 2);
    if (format === 'json') return `${body}\n`;
    return `// Generated by \`okjs icons\` — do not edit.
// Register with:
//   import { register } from '@kedem/okjs/toolkit/elements/ok-icon.ok.js';
//   import pack from './${name}';
//   register(pack, { complete: true });
export default ${body};
`;
}

/** Scan, fetch and serialize in one call. Returns { output, packs, dynamic, notFound, files }. */
export async function buildIconPack({
    src = [], include = [], set: defaultSet = 'lucide',
    api = 'https://api.iconify.design', format = 'js', out = 'icons.js',
    root = process.cwd(), fetchImpl = fetch
} = {}) {
    const files = src.length ? await matchFiles(src, root) : [];
    const wanted = new Map();
    const dynamic = [];
    const want = (set, name) => {
        if (!wanted.has(set)) wanted.set(set, new Set());
        wanted.get(set).add(name);
    };

    for (const file of files) {
        const source = await readFile(join(root, file), 'utf8');
        const result = scanSource(source, { file, defaultSet });
        for (const { set, name } of result.used) want(set, name);
        dynamic.push(...result.dynamic);
    }

    for (const entry of include) {
        const at = entry.indexOf(':');
        if (at === -1) want(defaultSet, entry);
        else want(entry.slice(0, at), entry.slice(at + 1));
    }

    const packs = [];
    const notFound = [];
    for (const [set, names] of wanted) {
        const result = await fetchSet(set, [...names], { api, fetchImpl });
        packs.push(result.pack);
        for (const name of result.notFound) notFound.push(`${set}:${name}`);
    }

    return {
        files, packs, dynamic, notFound,
        output: serialize(packs, { format, name: out.split('/').pop() })
    };
}
